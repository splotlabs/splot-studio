//! `studio-app` — the Splot Studio desktop window.
//!
//! The window is compiled from `ui/*.slint`. Callbacks and worker answers
//! become typed [`state::Intent`]s; [`state::AppState`] holds the queue of
//! files, the settings and the engine's answers as domain values, and the
//! window only ever receives display strings. All media work happens in
//! short-lived [`engine::Worker`] processes, one job at a time, run by the
//! [`session::Session`]; their events reach the Slint thread through
//! [`slint::invoke_from_event_loop`].
//!
//! The queue survives the app: it is journalled ([`journal`]) in the per-user
//! data folder ([`instance`]), which one running app owns at a time, and is
//! reconciled on the next launch ([`recovery`]). Encoding never continues
//! without the window; after a restart nothing starts by itself.
//!
