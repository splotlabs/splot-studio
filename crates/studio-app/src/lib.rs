//! `studio-app` — the Splot Studio desktop window.
//!
//! The window is compiled from `ui/*.slint`. Callbacks and worker answers
//! become typed [`state::Intent`]s; [`state::AppState`] holds the user's
//! choices and the engine's answers as domain values, and the window only
//! ever receives display strings. All media work happens in short-lived
//! [`engine::Worker`] processes; their events reach the Slint thread through
//! [`slint::invoke_from_event_loop`].
