/// The executable name, as sent to the engine.
pub const APP_NAME: &str = "splot-studio";

/// The commit a packaged build was made from (`cargo xtask package` sets
/// `SPLOT_STUDIO_BUILD_COMMIT`, with `-dirty` for uncommitted changes);
/// `None` for a development build.
pub const BUILD_COMMIT: Option<&str> = option_env!("SPLOT_STUDIO_BUILD_COMMIT");

/// The version shown in About: the package version, and the short commit of
/// a packaged build.
#[must_use]
pub fn display_version() -> String {
    let version = env!("CARGO_PKG_VERSION");
    match BUILD_COMMIT {
        Some(commit) => {
            let (hash, dirty) = commit
                .strip_suffix("-dirty")
                .map_or((commit, ""), |hash| (hash, "-dirty"));
            let short: String = hash.chars().take(10).collect();
            format!("{version} ({short}{dirty})")
        }
        None => format!("{version} (development build)"),
    }
}

/// The `--version` text: what this executable is, which protocol it speaks,
/// and the processor floor it checks. Needs no window or display.
#[must_use]
pub fn version_text() -> String {
    format!(
        "{APP_NAME} {}\ncommit: {}\nprotocol version: {}\n{}\n",
        env!("CARGO_PKG_VERSION"),
        BUILD_COMMIT.unwrap_or("not recorded (development build)"),
        studio_domain::protocol::PROTOCOL_VERSION,
        cpu::describe()
    )
}

/// What startup found before any window opens.
#[derive(Debug)]
pub enum Opening {
    /// This process owns the data folder (or has none and saves nothing).
    /// Boxed: it carries the whole restored journal.
    Owner(Box<Prepared>),
    /// Another running Splot Studio owns this data folder.
    AlreadyOpen(PathBuf),
}

/// The data folder's lock and the restored queue, ready for [`build`].
#[derive(Debug)]
pub struct Prepared {
    /// The data folder's lock; `None` when there is no usable folder.
    pub instance: Option<Instance>,
    /// Where to save the journal; `None` when this session must not.
    pub journal: Option<PathBuf>,
    /// What was restored, and what went wrong.
    pub startup: Startup,
}

/// Takes the data folder `dir` (see [`instance::data_dir`]), then reads and
/// reconciles its journal: a converting job becomes Interrupted and the
/// temporary file it announced is removed. Nothing else is started.
#[must_use]
pub fn prepare(dir: Result<PathBuf, String>) -> Opening {
    let unsaved = |why: String| {
        Opening::Owner(Box::new(Prepared {
            instance: None,
            journal: None,
            startup: Startup {
                recovered: None,
                problem: Some(JournalProblem::NoFolder(why)),
            },
        }))
    };
    let dir = match dir {
        Ok(dir) => dir,
        Err(why) => return unsaved(why),
    };
    let instance = match instance::acquire(&dir) {
        Acquired::Owner(instance) => instance,
        Acquired::AlreadyOpen => return Opening::AlreadyOpen(dir),
        Acquired::Failed(why) => return unsaved(why),
    };
    let path = dir.join(journal::FILE_NAME);
    let loaded = journal::load(&path);
    let save = loaded.may_save().then(|| path.clone());
    let (recovered, problem) = match loaded {
        Loaded::Missing => (None, None),
        Loaded::Found(journal) => {
            let mut recovered = recovery::recover(journal, &RealDisk);
            recovery::clean_up(&mut recovered);
            (Some(recovered), None)
        }
        Loaded::ViewUnreadable { journal, copy, .. } => {
            let mut recovered = recovery::recover(journal, &RealDisk);
            recovery::clean_up(&mut recovered);
            recovered.view.unreadable = Some(copy.clone());
            (Some(recovered), Some(JournalProblem::ViewUnreadable(copy)))
        }
        Loaded::TooNew { version } => (None, Some(JournalProblem::TooNew { path, version })),
        Loaded::MovedAside { to, .. } => (None, Some(JournalProblem::MovedAside(to))),
        Loaded::Unreadable { error } => (None, Some(JournalProblem::Unreadable { path, error })),
    };
    Opening::Owner(Box::new(Prepared {
        instance: Some(instance),
        journal: save,
        startup: Startup { recovered, problem },
    }))
}

/// The window and everything it drives. Dropping it (or [`Studio::run`]
/// returning) stops every worker and releases the data folder.
pub struct Studio {
    window: AppWindow,
    ctl: Rc<Controller>,
    _instance: Option<Instance>,
}

impl Studio {
    /// The window.
    #[must_use]
    pub const fn window(&self) -> &AppWindow {
        &self.window
    }

    /// Runs the event loop until the window closes or Quit, then records a
    /// converting file as interrupted, stops its worker and reaps it.
    /// Encoding never continues in the background.
    ///
    /// # Errors
    /// Returns the event loop's [`slint::PlatformError`].
    pub fn run(self) -> Result<(), slint::PlatformError> {
        let result = self.window.run();
        self.ctl.shutdown();
        result
    }
}

impl Drop for Studio {
    fn drop(&mut self) {
        self.ctl.shutdown();
    }
}

/// Creates the main window over `prepared`, with every callback wired and
/// the engine handshake started. `files` are added as if picked.
///
/// # Errors
/// Returns a [`slint::PlatformError`] when no window can be created.
pub fn build(prepared: Prepared, files: Vec<PathBuf>) -> Result<Studio, slint::PlatformError> {
    let engine = engine::sibling_path().map_err(|e| format!("cannot locate the app: {e}"));
    build_with_engine(prepared, files, engine)
}

/// Creates the main window and connects it to the specified engine.
///
/// # Errors
/// Returns a platform error if Slint cannot create the window.
pub fn build_with_engine(
    prepared: Prepared,
    files: Vec<PathBuf>,
    engine: Result<PathBuf, String>,
) -> Result<Studio, slint::PlatformError> {
    let window = new_window()?;
    let Prepared {
        instance,
        journal,
        startup,
    } = prepared;
    let mut state = AppState::new(startup);
    let writer =
        journal.and_then(
            |path| match journal::Writer::spawn(path, controller::journal_saved) {
                Ok(writer) => Some(writer),
                Err(e) => {
                    state.apply(
                        state::Intent::JournalSaved(Err(format!(
                            "no thread to save it with ({e})"
                        ))),
                        std::time::Instant::now(),
                        &RealDisk,
                    );
                    None
                }
            },
        );
    let session = Session::with_inspect_data_dir(
        state,
        engine,
        controller::post(),
        writer,
        instance.as_ref().map(|owner| owner.dir().to_owned()),
    );
    let ctl = Controller::start(&window, session, files);
    Ok(Studio {
        window,
        ctl,
        _instance: instance,
    })
}

/// Creates the window with its fixed labels and ranges, and nothing wired.
/// [`build`] uses it; renderer snapshots use it with [`render`] alone.
///
/// # Errors
/// Returns a [`slint::PlatformError`] when no window can be created.
pub fn new_window() -> Result<AppWindow, slint::PlatformError> {
    let window = AppWindow::new()?;
    window.set_app_version(display_version().into());
    window.set_output_labels(render::output_labels());
    let labels = |all: &[&str]| render::model(all.iter().map(|&l| SharedString::from(l)).collect());
    window.set_quality_labels(labels(&Quality::ALL.map(Quality::label)));
    window.set_priority_labels(labels(&Priority::ALL.map(Priority::label)));
    window.set_preset_min(0);
    window.set_preset_max(i32::from(SpeedPreset::MAX));
    window.set_crf_min(i32::from(Crf::MIN));
    window.set_crf_max(i32::from(Crf::MAX));
    // Windows puts the confirming button first; macOS and Linux desktops
    // put it last, next to the window edge.
    window.set_confirm_first(cfg!(windows));
    window.set_preview_note(present::preview::SDR_NOTE.into());
    window.set_workspace_labels(labels(
        &workspace::Workspace::OFFERED.map(workspace::Workspace::label),
    ));
    render::render_analysis(&window, &analysis::Analysis::new());
    Ok(window)
}

/// Wires the decoder overlay controls to the session.
pub fn bind_block_overlay(
    window: &AppWindow,
    send: impl Fn(analysis::BlockOverlayInput) + Clone + 'static,
) {
    use analysis::BlockOverlayInput as Input;
    let overlay = window.global::<BlockOverlay>();
    let action = |input: fn(i32) -> Input| {
        let send = send.clone();
        move |value| send(input(value))
    };
    overlay.on_choose(action(Input::Mode));
    overlay.on_choose_plane(action(Input::Plane));
    overlay.on_choose_tool(action(Input::Tool));
    overlay.on_select(action(Input::Select));
    overlay.on_move(action(Input::Move));
    let pick = send.clone();
    overlay.on_pick(move |x, y, width, height| {
        pick(Input::Pick {
            x,
            y,
            width,
            height,
        });
    });
    overlay.on_stop(move || send(Input::Stop));
}

/// Wires the Analyze workspace's callbacks to `send`, as the app does.
/// UI tests use it to drive a session the way the window does.
pub fn bind_analysis(window: &AppWindow, send: impl Fn(analysis::Input) + Clone + 'static) {
    use analysis::{Input, Step};
    render::timeline::bind(window, send.clone());
    render::blocks::bind(window, send.clone());
    let global = window.global::<Analysis>();
    let step = |step: NavStep| match step {
        // The window sends no `None`; treat it as no movement.
        NavStep::None => None,
        NavStep::Up => Some(Step::Up),
        NavStep::Down => Some(Step::Down),
        NavStep::PageUp => Some(Step::PageUp),
        NavStep::PageDown => Some(Step::PageDown),
        NavStep::Home => Some(Step::Home),
        NavStep::End => Some(Step::End),
        NavStep::Left => Some(Step::Left),
        NavStep::Right => Some(Step::Right),
    };
    let on = |input: Input| {
        let send = send.clone();
        move || send(input.clone())
    };
    global.on_close(on(Input::Close));
    global.on_reopen(on(Input::Reopen));
    global.on_cancel(on(Input::Cancel));
    global.on_resolve(on(Input::Resolve));
    global.on_select_at_cursor(on(Input::SelectAtCursor));
    global.on_toggle_bytes(on(Input::ToggleBytes));
    global.on_toggle_playback(on(Input::TogglePlayback));
    global.on_back(on(Input::Back));
    global.on_forward(on(Input::Forward));
    global.on_clear_filters(on(Input::ClearFilters));
    global.on_validate_stream(on(Input::Validate));
    global.on_clear_cache(on(Input::ClearCache));
    global.on_cancel_validation(on(Input::CancelValidation));
    let on = |input: fn(i32) -> Input| {
        let send = send.clone();
        move |value| send(input(value))
    };
    global.on_show(on(Input::Show));
    global.on_row_clicked(on(Input::RowClicked));
    global.on_scroll(on(Input::Scroll));
    global.on_byte_clicked(on(Input::ByteClicked));
    global.on_type_filter(on(Input::TypeFilter));
    global.on_layer_filter(on(Input::LayerFilter));
    let references = window.global::<References>();
    references.on_inspect({
        let send = send.clone();
        move || send(Input::InspectReferences)
    });
    references.on_cancel({
        let send = send.clone();
        move || send(Input::StopReferences)
    });
    references.on_follow(on(Input::FollowReference));
    global.on_evidence_view(on(Input::EvidenceView));
    global.on_evidence_severity(on(Input::EvidenceSeverity));
    global.on_evidence_layer(on(Input::EvidenceLayer));
    global.on_evidence_pick(on(Input::EvidencePick));
    global.on_evidence_page(on(Input::EvidencePage));
    global.on_finding_step(on(Input::FindingStep));
    global.on_evidence_move({
        let send = send.clone();
        move |s| {
            if let Some(s) = step(s) {
                send(Input::EvidenceMove(s));
            }
        }
    });
    global.on_evidence_search({
        let send = send.clone();
        move |text| send(Input::EvidenceSearch(text.to_string()))
    });
    global.on_evidence_rule({
        let send = send.clone();
        move |text| send(Input::EvidenceRule(text.to_string()))
    });
    global.on_move({
        let send = send.clone();
        move |s| {
            if let Some(s) = step(s) {
                send(Input::Move(s));
            }
        }
    });
    global.on_cursor({
        let send = send.clone();
        move |s| {
            if let Some(s) = step(s) {
                send(Input::Cursor(s));
            }
        }
    });
    global.on_scroll_to({
        let send = send.clone();
        move |share| send(Input::ScrollTo(share))
    });
    global.on_go_to({
        let send = send.clone();
        move |text| send(Input::GoTo(text.to_string()))
    });
    render::layers::bind(window, send);
}

/// The small window a second instance shows: Splot Studio is already open,
/// with Quit. Returns when it is closed.
///
/// # Errors
/// Returns a [`slint::PlatformError`] when no window can be created.
pub fn show_already_open() -> Result<(), slint::PlatformError> {
    show_notice(ALREADY_OPEN.0, ALREADY_OPEN.1)
}

/// The heading and message a second instance shows.
pub const ALREADY_OPEN: (&str, &str) = (
    "Splot Studio is already open",
    "Use the window that is already open. Only one can run at a time, so the list of files is \
     kept in one place.",
);

/// A small window with `heading`, `message` and Quit, shown instead of the
/// main window when the app cannot start. Returns when it is closed.
///
/// # Errors
/// Returns a [`slint::PlatformError`] when no window can be created.
pub fn show_notice(heading: &str, message: &str) -> Result<(), slint::PlatformError> {
    let window = NoticeWindow::new()?;
    window.set_heading(heading.into());
    window.set_message(message.into());
    window.on_quit_requested(|| {
        let _ = slint::quit_event_loop();
    });
    window.run()
}
