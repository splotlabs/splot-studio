/// The executable name, as sent to the engine.
pub const APP_NAME: &str = "splot-studio";

/// The request id of the startup `Hello`; probes and jobs count from 1.
const HELLO_ID: u64 = 0;

/// The window and everything it drives. Dropping it (or [`Studio::run`]
/// returning) stops every worker.
pub struct Studio {
    window: AppWindow,
    ctl: Rc<Controller>,
}

impl Studio {
    /// The window.
    #[must_use]
    pub const fn window(&self) -> &AppWindow {
        &self.window
    }

    /// Runs the event loop until the window closes or Quit, then stops any
    /// running job and reaps its worker. Encoding never continues in the
    /// background.
    ///
    /// # Errors
    /// Returns the event loop's [`slint::PlatformError`].
    pub fn run(self) -> Result<(), slint::PlatformError> {
        let result = self.window.run();
        self.ctl.shutdown();
        result
    }
}

impl Drop for Studio {
    fn drop(&mut self) {
        self.ctl.shutdown();
    }
}

/// Which request a worker serves.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Route {
    Hello,
    Probe(u64),
    Job(u64),
}

/// The Slint-thread side of the app: state, workers and timers.
struct Controller {
    window: slint::Weak<AppWindow>,
    state: RefCell<AppState>,
    engine: Result<PathBuf, String>,
    hello: RefCell<Option<Worker>>,
    probe: RefCell<Option<(u64, Worker)>>,
    job: RefCell<Option<(u64, Worker)>>,
    /// Ticks the elapsed time while a job runs; stopped otherwise.
    clock: Timer,
    /// Fires once [`activity::CANCEL_TIMEOUT`] after Cancel.
    cancel_deadline: Timer,
    shut_down: Cell<bool>,
}

thread_local! {
    /// Worker events arrive through `invoke_from_event_loop`, whose closures
    /// must be `Send`; they find the (non-`Send`) controller here, on the
    /// Slint thread.
    static CONTROLLER: RefCell<Weak<Controller>> = const { RefCell::new(Weak::new()) };
}

/// Creates the main window with every callback wired and the engine
/// handshake started. `source` behaves exactly like choosing that file in
/// the Open dialog.
///
/// # Errors
/// Returns a [`slint::PlatformError`] when no window can be created.
pub fn build(source: Option<PathBuf>) -> Result<Studio, slint::PlatformError> {
    let window = new_window()?;
    let ctl = Rc::new(Controller {
        window: window.as_weak(),
        state: RefCell::new(AppState::default()),
        engine: engine::sibling_path().map_err(|e| format!("cannot locate the app: {e}")),
        hello: RefCell::new(None),
        probe: RefCell::new(None),
        job: RefCell::new(None),
        clock: Timer::default(),
        cancel_deadline: Timer::default(),
        shut_down: Cell::new(false),
    });
    CONTROLLER.with(|c| *c.borrow_mut() = Rc::downgrade(&ctl));
    render(&window, &ctl.state.borrow(), Instant::now());

    let on = |intent: fn(i32) -> Intent| {
        let ctl = Rc::downgrade(&ctl);
        move |value| with(&ctl, |ctl| ctl.dispatch(intent(value)))
    };
    window.on_quality_selected(on(Intent::QualitySelected));
    window.on_priority_selected(on(Intent::PrioritySelected));
    window.on_output_selected(on(Intent::OutputSelected));
    window.on_track_selected(on(Intent::VideoTrackSelected));
    window.on_preset_edited(on(Intent::PresetEdited));
    window.on_crf_edited(on(Intent::CrfEdited));
    let on = |intent: fn() -> Intent| {
        let ctl = Rc::downgrade(&ctl);
        move || with(&ctl, |ctl| ctl.dispatch(intent()))
    };
    window.on_open_requested(on(|| Intent::OpenRequested));
    window.on_choose_destination_requested(on(|| Intent::ChooseDestinationRequested));
    window.on_encode_requested(on(|| Intent::EncodeRequested));
    window.on_omissions_confirmed(on(|| Intent::OmissionsConfirmed));
    window.on_omissions_declined(on(|| Intent::OmissionsDeclined));
    window.on_reset_requested(on(|| Intent::ResetRequested));
    window.on_cancel_requested({
        let ctl = Rc::downgrade(&ctl);
        move || with(&ctl, Controller::cancel_pressed)
    });
    window.on_reveal_requested({
        let ctl = Rc::downgrade(&ctl);
        move || with(&ctl, Controller::reveal)
    });
    window.on_fit_changed({
        let weak = window.as_weak();
        move || {
            fit(&weak);
            // Again once the compositor has answered: on GNOME Wayland a late
            // configure for the previous size can otherwise win.
            let weak = weak.clone();
            Timer::single_shot(FIT_SETTLE, move || fit(&weak));
        }
    });
    window.on_quit_requested(|| {
        // Only fails when no event loop is running, so there is nothing to quit.
        let _ = slint::quit_event_loop();
    });

    ctl.start_hello();
    if let Some(path) = source {
        ctl.dispatch(Intent::PickFinished(Some(path)));
    }
    Ok(Studio { window, ctl })
}

/// Creates the window with its fixed labels and ranges, and nothing wired.
/// [`build`] uses it; renderer snapshots use it with [`render`] alone.
///
/// # Errors
/// Returns a [`slint::PlatformError`] when no window can be created.
pub fn new_window() -> Result<AppWindow, slint::PlatformError> {
    let window = AppWindow::new()?;
    window.set_app_version(env!("CARGO_PKG_VERSION").into());
    let labels: Vec<SharedString> = OutputKind::ALL.iter().map(|k| k.label().into()).collect();
    window.set_output_labels(model(labels));
    let labels = |all: &[&str]| model(all.iter().map(|&l| SharedString::from(l)).collect());
    window.set_quality_labels(labels(&Quality::ALL.map(Quality::label)));
    window.set_priority_labels(labels(&Priority::ALL.map(Priority::label)));
    window.set_preset_min(0);
    window.set_preset_max(i32::from(SpeedPreset::MAX));
    window.set_crf_min(i32::from(Crf::MIN));
    window.set_crf_max(i32::from(Crf::MAX));
    // Windows puts the confirming button first; macOS and Linux desktops
    // put it last, next to the window edge.
    window.set_confirm_first(cfg!(windows));
    Ok(window)
}

/// How long after a size change the fitted size is asserted once more.
const FIT_SETTLE: Duration = Duration::from_millis(300);

/// Sizes the window to its content (the window is the card).
fn fit(window: &slint::Weak<AppWindow>) {
    if let Some(window) = window.upgrade() {
        let size = slint::LogicalSize::new(window.get_fitted_width(), window.get_fitted_height());
        if size.width > 0.0 && size.height > 0.0 {
            window.window().set_size(size);
        }
    }
}

fn with(ctl: &Weak<Controller>, f: impl FnOnce(&Rc<Controller>)) {
    if let Some(ctl) = ctl.upgrade() {
        f(&ctl);
    }
}

impl Controller {
    /// Applies an intent, performs its effect and redraws what changed.
    fn dispatch(self: &Rc<Self>, intent: Intent) {
        let effect = self.state.borrow_mut().apply(intent, Instant::now());
        let Some(window) = self.window.upgrade() else {
            return;
        };
        let redraw = match effect {
            Effect::None => Changed::Phase,
            Effect::ShowOpenDialog => {
                self.show_open_dialog(&window);
                Changed::Phase
            }
            Effect::ShowSaveDialog {
                directory,
                file_name,
                output,
            } => {
                self.show_save_dialog(&window, directory, &file_name, output);
                Changed::Phase
            }
            Effect::Probe(request) => {
                self.start_probe(request);
                Changed::Phase
            }
            Effect::Start { id, job } => {
                self.start_job(id, Command::Start { job });
                Changed::Phase
            }
            Effect::Job { id, step, reprobe } => {
                self.job_effect(id, step.effect);
                match reprobe {
                    Some(request) => {
                        self.start_probe(request);
                        Changed::Phase
                    }
                    None => step.changed,
                }
            }
        };
        let now = Instant::now();
        match redraw {
            Changed::Nothing => {}
            Changed::Counters => {
                if let Some((_, activity)) = self.state.borrow().job() {
                    render_counters(&window, activity, now);
                }
            }
            Changed::Phase => {
                self.check_destination();
                render(&window, &self.state.borrow(), now);
            }
        }
    }

    /// Refreshes whether the destination exists, unless a job owns it.
    fn check_destination(&self) {
        let mut state = self.state.borrow_mut();
        if state.job_running() {
            return;
        }
        if let Some(path) = state.destination().map(|d| d.path.clone()) {
            // An unreadable answer is "unknown"; the engine refuses to
            // replace a file regardless.
            state.note_destination_exists(path.try_exists().unwrap_or(false));
        }
    }

    fn spawn(&self, route: Route) -> Result<Worker, String> {
        let engine = self.engine.as_ref().map_err(Clone::clone)?;
        Worker::spawn(engine, move |delivery| {
            // Fails only once the event loop is gone and nobody listens.
            let _ = slint::invoke_from_event_loop(move || deliver(route, delivery));
        })
        .map_err(|e| e.to_string())
    }

    fn start_hello(&self) {
        let client = BuildIdentity {
            name: APP_NAME.to_owned(),
            version: env!("CARGO_PKG_VERSION").to_owned(),
        };
        let started = self.spawn(Route::Hello).and_then(|mut worker| {
            worker
                .send(HELLO_ID, Command::Hello { client })
                .map_err(|e| format!("could not send the handshake: {e}"))?;
            // End of input tells the worker to exit once it has answered.
            worker.close_input();
            Ok(worker)
        });
        match started {
            Ok(worker) => *self.hello.borrow_mut() = Some(worker),
            Err(e) => {
                let status = match &self.engine {
                    Ok(path) if !path.exists() => EngineStatus::NotFound(path.clone()),
                    _ => EngineStatus::Failed(e),
                };
                self.engine_answered(&status);
            }
        }
    }

    fn engine_answered(&self, status: &EngineStatus) {
        if let Some(window) = self.window.upgrade() {
            show_engine(&window, status);
        }
        // The dispatch needs an Rc; the controller is always held by one.
        if let Some(ctl) = CONTROLLER.with(|c| c.borrow().upgrade()) {
            let answer = match status {
                EngineStatus::Ready { capabilities, .. } => Ok(capabilities.clone()),
                EngineStatus::NotFound(path) => Err(format!(
                    "The encoding engine is missing ({}). Reinstall Splot Studio.",
                    path.display()
                )),
                EngineStatus::Incompatible(why) => Err(format!(
                    "The encoding engine does not match this app: {why}. Reinstall Splot Studio."
                )),
                EngineStatus::Failed(why) => {
                    Err(format!("The encoding engine did not start: {why}."))
                }
            };
            ctl.dispatch(Intent::EngineAnswered(answer));
        }
    }

    fn start_probe(self: &Rc<Self>, request: ProbeRequest) {
        let ProbeRequest {
            id,
            path,
            video_stream,
        } = request;
        // One metadata read for the file card; the engine reads the rest.
        let size = std::fs::metadata(&path).ok().map(|m| m.len());
        self.state.borrow_mut().note_source_size(size);
        // Replacing an older probe drops its worker, which then exits.
        let started = self.spawn(Route::Probe(id)).and_then(|mut worker| {
            let source = studio_domain::job::WirePath::from_path(&path);
            worker
                .send(
                    id,
                    Command::Probe {
                        source,
                        video_stream,
                    },
                )
                .map_err(|e| format!("could not ask the engine: {e}"))?;
            worker.close_input();
            Ok(worker)
        });
        match started {
            Ok(worker) => *self.probe.borrow_mut() = Some((id, worker)),
            Err(message) => {
                *self.probe.borrow_mut() = None;
                self.dispatch(Intent::ProbeAnswered {
                    id,
                    result: Err(ProbeFailure::other(message)),
                });
            }
        }
    }

    fn start_job(self: &Rc<Self>, id: u64, start: Command) {
        let started = self.spawn(Route::Job(id)).and_then(|mut worker| {
            worker
                .send(id, start)
                .map_err(|e| format!("could not send the job: {e}"))?;
            Ok(worker)
        });
        match started {
            Ok(worker) => {
                *self.job.borrow_mut() = Some((id, worker));
                let weak = CONTROLLER.with(|c| c.borrow().clone());
                self.clock
                    .start(TimerMode::Repeated, Duration::from_secs(1), move || {
                        with(&weak, Controller::tick);
                    });
            }
            Err(detail) => self.dispatch(Intent::Job {
                id,
                input: activity::Input::WorkerEnded { detail },
            }),
        }
    }

    fn job_effect(self: &Rc<Self>, id: u64, effect: activity::Effect) {
        if !self.state.borrow().job_running() {
            self.clock.stop();
            self.cancel_deadline.stop();
        }
        let mut job = self.job.borrow_mut();
        let Some((_, worker)) = job.as_mut().filter(|(current, _)| *current == id) else {
            return;
        };
        match effect {
            activity::Effect::None => {}
            activity::Effect::SendCancel => {
                // Cancel carries the job's request id: it is about that job.
                if worker.send(id, Command::Cancel).is_err() {
                    // The worker is already gone; its end of stream decides.
                    worker.close_input();
                }
                let weak = CONTROLLER.with(|c| c.borrow().clone());
                self.cancel_deadline.start(
                    TimerMode::SingleShot,
                    activity::CANCEL_TIMEOUT,
                    move || {
                        with(&weak, |ctl| {
                            ctl.dispatch(Intent::Job {
                                id,
                                input: activity::Input::CancelTimedOut,
                            });
                        });
                    },
                );
            }
            activity::Effect::CloseInput => worker.close_input(),
            activity::Effect::Kill => worker.kill(),
        }
    }

    fn cancel_pressed(self: &Rc<Self>) {
        let id = self.state.borrow().job().map(|(id, _)| id);
        if let Some(id) = id {
            self.dispatch(Intent::Job {
                id,
                input: activity::Input::CancelPressed,
            });
        }
    }

    fn tick(self: &Rc<Self>) {
        if let (Some(window), Some((_, activity))) =
            (self.window.upgrade(), self.state.borrow().job())
        {
            window.set_elapsed_text(present::elapsed(activity.elapsed(Instant::now())).into());
        }
    }

    /// Opens the published file's folder off the Slint thread; a failure is
    /// shown under the result.
    fn reveal(self: &Rc<Self>) {
        let Some(path) = self
            .state
            .borrow()
            .job()
            .filter(|(_, a)| matches!(a.phase(), Phase::Completed(_)))
            .map(|(_, a)| a.destination().to_path_buf())
        else {
            return;
        };
        let weak = self.window.clone();
        if let Some(window) = weak.upgrade() {
            window.set_reveal_error(SharedString::new());
        }
        let spawned = std::thread::Builder::new()
            .name("show-in-folder".to_owned())
            .spawn(move || {
                if let Err(e) = reveal::show_in_folder(&path) {
                    let text = format!("Could not show the file in its folder: {e}");
                    let _ = weak.upgrade_in_event_loop(move |w| w.set_reveal_error(text.into()));
                }
            });
        if let (Err(e), Some(window)) = (spawned, self.window.upgrade()) {
            window.set_reveal_error(format!("Could not show the file in its folder: {e}").into());
        }
    }

    /// Shows the native Open dialog without blocking the event loop: rfd's
    /// future completes on its own thread (portal) or the native panel, and
    /// is awaited on the Slint event loop.
    fn show_open_dialog(self: &Rc<Self>, window: &AppWindow) {
        let dialog = rfd::AsyncFileDialog::new()
            .set_title("Open Source")
            .set_parent(&window.window().window_handle());
        // A convenience, not a capability claim: the engine decides what it
        // can read. macOS merges all filters into one allow-list, where
        // "All files" would not widen it; leave that panel unfiltered.
        #[cfg(not(target_os = "macos"))]
        let dialog = dialog
            .add_filter(
                "Video files",
                &["mp4", "m4v", "mov", "mkv", "webm", "ts", "avi", "y4m"],
            )
            .add_filter("All files", &["*"]);
        let picked = dialog.pick_file();
        let weak = Rc::downgrade(self);
        let spawned = slint::spawn_local(async move {
            let path = picked.await.map(|file| file.path().to_path_buf());
            with(&weak, |ctl| ctl.dispatch(Intent::PickFinished(path)));
        });
        if spawned.is_err() {
            // No event loop to drive the dialog: treat it as cancelled.
            self.dispatch(Intent::PickFinished(None));
        }
    }

    fn show_save_dialog(
        self: &Rc<Self>,
        window: &AppWindow,
        directory: Option<PathBuf>,
        file_name: &str,
        output: OutputKind,
    ) {
        let mut dialog = rfd::AsyncFileDialog::new()
            .set_title("Choose Output")
            .set_parent(&window.window().window_handle())
            .set_file_name(file_name)
            .add_filter(output.label(), &[output.extension()]);
        if let Some(directory) = directory {
            dialog = dialog.set_directory(directory);
        }
        let picked = dialog.save_file();
        let weak = Rc::downgrade(self);
        let spawned = slint::spawn_local(async move {
            let path = picked.await.map(|file| file.path().to_path_buf());
            with(&weak, |ctl| ctl.dispatch(Intent::DestinationPicked(path)));
        });
        if spawned.is_err() {
            self.dispatch(Intent::DestinationPicked(None));
        }
    }

    /// Stops every worker: a running job is cancelled by closing its input
    /// and killed if it has not exited within [`engine::EXIT_GRACE`].
    fn shutdown(&self) {
        if self.shut_down.replace(true) {
            return;
        }
        self.clock.stop();
        self.cancel_deadline.stop();
        let workers = [
            self.job.take().map(|(_, w)| w),
            self.probe.take().map(|(_, w)| w),
            self.hello.take(),
        ];
        for worker in workers.into_iter().flatten() {
            worker.shutdown(engine::EXIT_GRACE);
        }
    }
}

/// Routes one worker delivery on the Slint thread.
fn deliver(route: Route, delivery: Delivery) {
    let Some(ctl) = CONTROLLER.with(|c| c.borrow().upgrade()) else {
        return;
    };
    if ctl.shut_down.get() {
        return;
    }
    match route {
        Route::Hello => {
            // Only the first delivery answers; the stream ending afterwards
            // is the worker exiting as asked. Dropping it lets it be reaped.
            let worker = ctl.hello.borrow_mut().take();
            if worker.is_some() {
                ctl.engine_answered(&EngineStatus::from_hello(delivery));
            }
        }
        Route::Probe(id) => {
            let result = match delivery {
                Delivery::Event(e) if e.request_id != id => return,
                Delivery::Event(e) => match e.body {
                    Event::Probed { facts } => Ok(facts),
                    Event::Failed { failure } => Err(ProbeFailure::from(failure)),
                    Event::Error { message, .. } => Err(ProbeFailure::other(format!(
                        "The engine refused: {message}"
                    ))),
                    _ => return,
                },
                Delivery::Ended(ending) => {
                    let mut probe = ctl.probe.borrow_mut();
                    if probe.as_ref().is_some_and(|(current, _)| *current == id) {
                        *probe = None;
                    }
                    Err(ProbeFailure::other(format!(
                        "The engine stopped without answering ({}).",
                        ending_text(&ending)
                    )))
                }
            };
            // A probe that already answered ignores this one.
            ctl.dispatch(Intent::ProbeAnswered { id, result });
        }
        Route::Job(id) => {
            let input = match delivery {
                Delivery::Event(e) if e.request_id != id => {
                    eprintln!(
                        "{APP_NAME}: ignoring an event for request {} during job {id}",
                        e.request_id
                    );
                    return;
                }
                Delivery::Event(e) => activity::Input::Event(e.body),
                Delivery::Ended(ending) => {
                    let mut job = ctl.job.borrow_mut();
                    if job.as_ref().is_some_and(|(current, _)| *current == id) {
                        *job = None;
                    }
                    activity::Input::WorkerEnded {
                        detail: ending_text(&ending),
                    }
                }
            };
            ctl.dispatch(Intent::Job { id, input });
        }
    }
}

fn ending_text(ending: &Ending) -> String {
    match &ending.error {
        None => ending.exit.clone(),
        Some(e) => format!("{e}; {}", ending.exit),
    }
}

fn show_engine(window: &AppWindow, status: &EngineStatus) {
    window.set_engine_identity(
        match status {
            EngineStatus::Ready { engine, .. } => format!(
                "{} {} · protocol {}",
                engine.name,
                engine.version,
                studio_domain::protocol::PROTOCOL_VERSION
            ),
            other => other.summary(),
        }
        .into(),
    );
}

const fn tone(tone: present::Tone) -> Tone {
    match tone {
        present::Tone::Neutral => Tone::Neutral,
        present::Tone::Success => Tone::Success,
        present::Tone::Warning => Tone::Warning,
        present::Tone::Error => Tone::Error,
    }
}

fn model<T: Clone + 'static>(rows: Vec<T>) -> ModelRc<T> {
    ModelRc::new(VecModel::from(rows))
}

/// Pushes the whole state into the window. Used for user actions and phase
/// changes; progress updates use [`render_counters`] instead.
///
/// Public so renderer snapshots can show a state without running workers.
pub fn render(window: &AppWindow, state: &AppState, now: Instant) {
    let settings = state.settings();
    window.set_output_index(state.output_index());
    window.set_preset(i32::from(settings.preset.get()));
    window.set_crf(i32::from(settings.crf.get()));
    window.set_quality_index(simple::index(&Quality::ALL, Quality::of(settings.crf)));
    let priority = Priority::of(settings.preset);
    window.set_priority_index(simple::index(&Priority::ALL, priority));
    window.set_priority_caption(
        priority
            .map_or("A speed preset set in Advanced.", Priority::description)
            .into(),
    );
    window.set_locked(state.job_running());

    render_source(window, state);
    window.set_empty_caption(present::empty_caption(state.capabilities()).into());
    window.set_media_tool_line(present::media_tool(state.capabilities()).into());
    render_confirmation(window, state);

    let destination = state.destination();
    window.set_has_destination(destination.is_some());
    window.set_destination_path(
        destination
            .map_or_else(String::new, |d| d.path.display().to_string())
            .into(),
    );
    window.set_destination_help(
        match destination {
            None => "",
            Some(d) if d.chosen => "Chosen by you. An existing file is never replaced.",
            Some(_) => "Next to the source. An existing file is never replaced.",
        }
        .into(),
    );
    window.set_destination_line(
        match destination {
            None => String::new(),
            Some(d) if d.chosen => format!("Saves video only to {}", d.path.display()),
            Some(d) => format!(
                "Saves video only as {}, next to the source",
                present::file_name(&d.path)
            ),
        }
        .into(),
    );
    window.set_destination_warning(
        if destination.is_some_and(|d| d.exists) {
            "A file already exists here. Choose another name, or move that file away."
        } else {
            ""
        }
        .into(),
    );

    let blocker = state.blocker();
    window.set_can_encode(blocker.is_none());
    window.set_encode_status_tone(match blocker.as_ref().map(|b| b.severity) {
        Some(Severity::Problem) => Tone::Error,
        Some(Severity::Warning) => Tone::Warning,
        Some(Severity::Info) | None => Tone::Neutral,
    });
    window.set_encode_status(
        blocker
            .map_or_else(
                || {
                    let name =
                        destination.map_or_else(String::new, |d| present::file_name(&d.path));
                    format!("Ready to convert to {name}")
                },
                |b| b.text,
            )
            .into(),
    );

    match state.job() {
        None => window.set_job_view(JobView::None),
        Some((_, activity)) => render_job(window, activity, now),
    }
}

fn render_source(window: &AppWindow, state: &AppState) {
    let source = state.source();
    let (name, path) = source.path().map_or_else(Default::default, |p| {
        (present::file_name(p), p.display().to_string())
    });
    window.set_source_name(name.into());
    window.set_source_path(path.into());
    // While the same file is read again, its last facts stay in place so the
    // window does not jump; Convert waits for the new ones.
    let shown = source.shown_facts();
    window.set_source_line(present::source_line(shown, state.source_size()).into());
    window.set_source_view(match source {
        Source::None => SourceView::None,
        Source::Probing { .. } => SourceView::Probing,
        Source::Ready { .. } => SourceView::Ready,
        Source::Unreadable { .. } => SourceView::Unreadable,
    });
    let (problem, problem_tone) = match source {
        Source::Unreadable { failure, .. } => (
            present::probe_problem(failure),
            if failure.code == Some(studio_domain::job::FailureCode::MediaToolMissing) {
                Tone::Warning
            } else {
                Tone::Error
            },
        ),
        _ => (String::new(), Tone::Neutral),
    };
    window.set_source_problem(problem.into());
    window.set_source_problem_tone(problem_tone);
    window.set_has_source_facts(shown.is_some());
    let rows: Vec<Fact> = shown
        .map_or_else(Vec::new, present::facts)
        .into_iter()
        .map(|(label, value)| Fact {
            label: label.into(),
            value: value.into(),
        })
        .collect();
    window.set_source_facts(model(rows));
    let disclosures: Vec<SharedString> = shown
        .map_or(&[][..], |f| f.disclosures.as_slice())
        .iter()
        .map(|&d| SharedString::from(present::disclosure(d)))
        .collect();
    window.set_source_disclosures(model(disclosures));
    window.set_omission_summary(
        shown
            .map_or_else(String::new, |f| {
                present::omission_summary(&f.omissions, state::attached_pictures(f))
            })
            .into(),
    );

    let picker = state.track_picker();
    window.set_has_track_picker(picker.is_some());
    let (labels, index, note) = picker.map_or_else(
        || (Vec::new(), -1, String::new()),
        |p| {
            (
                p.tracks
                    .iter()
                    .map(|t| SharedString::from(present::track(t)))
                    .collect(),
                p.selected.and_then(|i| i32::try_from(i).ok()).unwrap_or(-1),
                present::attached_note(&p.attached),
            )
        },
    );
    window.set_track_labels(model(labels));
    window.set_track_index(index);
    window.set_track_note(note.into());
}

/// Shows or closes the video-only confirmation to match the state.
fn render_confirmation(window: &AppWindow, state: &AppState) {
    match state.confirmation() {
        Some(c) => {
            window.set_sheet_body(
                present::omission_question(
                    &c.omissions,
                    c.attached_pictures,
                    c.job.settings.output,
                )
                .into(),
            );
            if !window.get_sheet_open() {
                window.invoke_show_sheet();
            }
        }
        None if window.get_sheet_open() => window.invoke_close_sheet(),
        None => {}
    }
}

fn render_job(window: &AppWindow, activity: &activity::Activity, now: Instant) {
    let view = match activity.phase() {
        Phase::Starting | Phase::Running(_) => JobView::Running,
        Phase::Cancelling { .. } => JobView::Cancelling,
        Phase::Completed(_) => JobView::Completed,
        Phase::Cancelled => JobView::Cancelled,
        Phase::Failed(_) => JobView::Failed,
        Phase::Lost(_) => JobView::Lost,
    };
    let (headline, headline_tone) = present::headline(activity);
    window.set_job_view(view);
    window.set_job_headline(headline.into());
    window.set_job_tone(tone(headline_tone));
    window.set_job_detail(present::detail(activity).into());
    let checks: Vec<CheckRow> = match activity.phase() {
        Phase::Completed(report) => report
            .checks
            .iter()
            .map(|c| {
                let (name, outcome, detail, t) = present::check(c);
                CheckRow {
                    name: name.into(),
                    outcome: outcome.into(),
                    detail: detail.into(),
                    tone: tone(t),
                }
            })
            .collect(),
        _ => Vec::new(),
    };
    window.set_job_checks(model(checks));
    if !matches!(activity.phase(), Phase::Completed(_)) {
        window.set_reveal_error(SharedString::new());
    }
    render_counters(window, activity, now);
}

/// Updates only the counters, the progress bar and the elapsed time.
pub fn render_counters(window: &AppWindow, activity: &activity::Activity, now: Instant) {
    let fraction = activity.fraction();
    window.set_progress_known(fraction.is_some());
    window.set_progress_fraction(fraction.unwrap_or(0.0));
    window.set_progress_text(
        if activity.before_first_frame() {
            "Waiting for the first frame".to_owned()
        } else {
            present::progress_text(activity)
        }
        .into(),
    );
    window.set_progress_line(present::counters(activity).into());
    window.set_elapsed_text(present::elapsed(activity.elapsed(now)).into());
}
