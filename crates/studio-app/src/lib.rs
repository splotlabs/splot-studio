/// The executable name, as sent to the engine.
pub const APP_NAME: &str = "splot-studio";

/// Creates the main window with every callback wired and the engine handshake
/// started. Call [`ComponentHandle::run`] on the result.
///
/// # Errors
/// Returns a [`slint::PlatformError`] when no window can be created.
pub fn build() -> Result<AppWindow, slint::PlatformError> {
    let window = AppWindow::new()?;
    let state = Rc::new(RefCell::new(AppState::default()));

    window.set_app_version(env!("CARGO_PKG_VERSION").into());
    let labels: Vec<SharedString> = OutputKind::ALL.iter().map(|k| k.label().into()).collect();
    window.set_output_labels(ModelRc::new(VecModel::from(labels)));
    window.set_preset_min(0);
    window.set_preset_max(i32::from(SpeedPreset::MAX));
    window.set_crf_min(i32::from(Crf::MIN));
    window.set_crf_max(i32::from(Crf::MAX));
    sync(&window, &state.borrow());

    let on = |intent: fn(i32) -> Intent| {
        let (window, state) = (window.as_weak(), Rc::clone(&state));
        move |value| dispatch(&window, &state, intent(value))
    };
    window.on_output_selected(on(Intent::OutputSelected));
    window.on_preset_edited(on(Intent::PresetEdited));
    window.on_crf_edited(on(Intent::CrfEdited));
    window.on_open_requested({
        let (window, state) = (window.as_weak(), Rc::clone(&state));
        move || dispatch(&window, &state, Intent::OpenRequested)
    });
    window.on_quit_requested(|| {
        // Only fails when no event loop is running, so there is nothing to quit.
        let _ = slint::quit_event_loop();
    });

    start_handshake(&window);
    Ok(window)
}

/// Applies an intent, performs its effect and re-synchronises the window.
fn dispatch(window: &slint::Weak<AppWindow>, state: &Rc<RefCell<AppState>>, intent: Intent) {
    let effect = state.borrow_mut().apply(intent);
    let Some(strong) = window.upgrade() else {
        return;
    };
    sync(&strong, &state.borrow());
    if effect == Effect::ShowOpenDialog {
        show_open_dialog(&strong, window, state);
    }
}

/// Pushes the state into the window's properties.
fn sync(window: &AppWindow, state: &AppState) {
    let settings = state.settings();
    window.set_output_index(state.output_index());
    window.set_preset(i32::from(settings.preset.get()));
    window.set_crf(i32::from(settings.crf.get()));
    let (name, path) = state.source_display().unwrap_or_default();
    window.set_has_source(state.source().is_some());
    window.set_source_name(name.into());
    window.set_source_path(path.into());
}

/// Shows the native Open dialog without blocking the event loop: rfd's future
/// completes on its own thread (portal) or the native panel, and is awaited
/// on the Slint event loop.
fn show_open_dialog(
    window: &AppWindow,
    weak: &slint::Weak<AppWindow>,
    state: &Rc<RefCell<AppState>>,
) {
    let dialog = rfd::AsyncFileDialog::new()
        .set_title("Open Source")
        .set_parent(&window.window().window_handle())
        .pick_file();
    let (weak_in, state_in) = (weak.clone(), Rc::clone(state));
    let spawned = slint::spawn_local(async move {
        let path = dialog.await.map(|file| file.path().to_path_buf());
        dispatch(&weak_in, &state_in, Intent::PickFinished(path));
    });
    if spawned.is_err() {
        // No event loop to drive the dialog: treat it as cancelled.
        dispatch(weak, state, Intent::PickFinished(None));
    }
}

/// Runs the engine handshake on a worker thread and shows the result.
fn start_handshake(window: &AppWindow) {
    let weak = window.as_weak();
    let client = BuildIdentity {
        name: APP_NAME.to_owned(),
        version: env!("CARGO_PKG_VERSION").to_owned(),
    };
    let spawned = std::thread::Builder::new()
        .name("engine-handshake".to_owned())
        .spawn(move || {
            let status = match engine::sibling_path() {
                Ok(path) => engine::handshake(&path, client),
                Err(e) => EngineStatus::Failed(format!("cannot locate the app: {e}")),
            };
            // Fails only once the window is gone, when nobody needs the answer.
            let _ = weak.upgrade_in_event_loop(move |window| show_engine(&window, &status));
        });
    if let Err(e) = spawned {
        show_engine(
            window,
            &EngineStatus::Failed(format!("cannot start the handshake thread: {e}")),
        );
    }
}

fn show_engine(window: &AppWindow, status: &EngineStatus) {
    let tone = match status {
        EngineStatus::Ready { encode_outputs, .. } if encode_outputs.is_empty() => Tone::Warning,
        EngineStatus::Ready { .. } => Tone::Success,
        EngineStatus::NotFound(_) | EngineStatus::Incompatible(_) | EngineStatus::Failed(_) => {
            Tone::Error
        }
    };
    window.set_engine_text(status.summary().into());
    window.set_engine_tone(tone);
}
