//! `studio-app` — the Splot Studio desktop window.
//!
//! The window is compiled from `ui/*.slint`. Callbacks become typed
//! [`state::Intent`]s handled here; [`state::AppState`] holds the user's
//! choices as domain values and the window only ever receives display strings.
//! Launch is cheap: no codec, `FFmpeg`, preview or worker pool, just one
//! engine handshake on a background thread.
//!
